def supported_languages() -> tuple[str, ...]:
    return _SUPPORTED


def scaffold(name: str, language: str, programs_dir: str | None = None) -> dict[str, Any]:
    """生成一个新混合语言模块，返回生成结果。"""
    name = str(name or "").strip()
    language = str(language or "").strip().lower()
    if not _NAME_RE.match(name):
        raise ValueError("模块名只能包含字母、数字、- 和 _，且以字母开头")
    if language not in _LANGUAGES:
        raise ValueError(f"不支持的语言: {language}（可选: {', '.join(_SUPPORTED)}）")

    root = Path(programs_dir or _DEFAULT_PROGRAMS_DIR).resolve()
    module_dir = root / name
    if module_dir.exists():
        raise ValueError(f"目录已存在: {module_dir}")

    source_name, build_command, _toolchain = _LANGUAGES[language]
    executable = "worker.py" if language == "python" else f"{name}_exec"
    module_dir.mkdir(parents=True)

    source = module_dir / source_name
    source.write_text(_TEMPLATES[language].replace("%NAME%", name), encoding="utf-8")
    if language == "python":
        os.chmod(source, 0o755)

    manifest = {
        "name": name,
        "language": language,
        "protocol": "bhl",
        "description": f"{name} BHL module (generated by butler hybrid new)",
        "source": [source_name],
        "build": build_command.replace("{output}", executable),
        "executable": executable,
        "methods": ["ping", "echo"],
    }
    manifest_path = module_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=4) + "\n", encoding="utf-8"
    )

    return {
        "name": name,
        "language": language,
        "dir": str(module_dir),
        "manifest": str(manifest_path),
        "source": str(source),
        "build": bool(build_command),
    }
